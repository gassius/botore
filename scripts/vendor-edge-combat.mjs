#!/usr/bin/env node
/**
 * Vendor pure combat packages into supabase/functions/_shared/botore for the
 * Deno Edge runtime. Re-run after changing rng / replay / combat-engine.
 *
 * Usage: node scripts/vendor-edge-combat.mjs
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outRoot = join(root, 'supabase/functions/_shared/botore');
const require = createRequire(import.meta.url);

function fail(msg) {
  console.error(`vendor-edge-combat FAIL: ${msg}`);
  process.exit(1);
}

function ensureBuilt(pkgDir) {
  const distIndex = join(root, pkgDir, 'dist/index.js');
  if (!existsSync(distIndex)) {
    const res = spawnSync(
      'pnpm',
      ['exec', 'turbo', 'run', 'build', `--filter=@botore/${pkgDir.split('/').pop()}`],
      {
        cwd: root,
        encoding: 'utf8',
        stdio: 'inherit',
      },
    );
    if (res.status !== 0) fail(`build failed for ${pkgDir}`);
  }
  if (!existsSync(distIndex)) fail(`missing ${distIndex}`);
}

function rewriteImports(source, map) {
  let out = source;
  for (const [from, to] of Object.entries(map)) {
    out = out.split(from).join(to);
  }
  return out;
}

function writeJs(relPath, contents) {
  const abs = join(outRoot, relPath);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, contents);
}

console.log('==> vendor edge combat packages');

for (const pkg of ['packages/rng', 'packages/replay', 'packages/combat-engine']) {
  ensureBuilt(pkg);
}

rmSync(outRoot, { recursive: true, force: true });
mkdirSync(outRoot, { recursive: true });

// --- @noble/hashes (sha2 dependency closure) --------------------------------
let nobleRoot;
try {
  nobleRoot = dirname(require.resolve('@noble/hashes/sha2.js'));
} catch {
  // pnpm may hoist under a package; try rng's resolution
  const rngRequire = createRequire(join(root, 'packages/rng/package.json'));
  nobleRoot = dirname(rngRequire.resolve('@noble/hashes/sha2.js'));
}

const nobleFiles = ['sha2.js', '_md.js', '_u64.js', 'utils.js'];
for (const file of nobleFiles) {
  const src = join(nobleRoot, file);
  if (!existsSync(src)) fail(`missing noble file ${src}`);
  cpSync(src, join(outRoot, 'noble-hashes', file));
}
console.log('vendored @noble/hashes sha2 closure');

// --- rng --------------------------------------------------------------------
const rngMap = {
  "'@noble/hashes/sha2.js'": "'../noble-hashes/sha2.js'",
  '"@noble/hashes/sha2.js"': '"../noble-hashes/sha2.js"',
};
for (const file of ['index.js', 'seed.js', 'sha256-counter.js']) {
  const raw = readFileSync(join(root, 'packages/rng/dist', file), 'utf8');
  writeJs(join('rng', file), rewriteImports(raw, rngMap));
}
console.log('vendored @botore/rng');

// --- replay -----------------------------------------------------------------
{
  const raw = readFileSync(join(root, 'packages/replay/dist/index.js'), 'utf8');
  writeJs(
    'replay/index.js',
    rewriteImports(raw, {
      "'@noble/hashes/sha2.js'": "'../noble-hashes/sha2.js'",
      '"@noble/hashes/sha2.js"': '"../noble-hashes/sha2.js"',
    }),
  );
}
console.log('vendored @botore/replay');

// --- combat-engine ----------------------------------------------------------
{
  const raw = readFileSync(join(root, 'packages/combat-engine/dist/index.js'), 'utf8');
  writeJs(
    'combat-engine/index.js',
    rewriteImports(raw, {
      "'@botore/rng'": "'../rng/index.js'",
      '"@botore/rng"': '"../rng/index.js"',
      "'@botore/replay'": "'../replay/index.js'",
      '"@botore/replay"': '"../replay/index.js"',
    }),
  );
}
console.log('vendored @botore/combat-engine');

writeFileSync(
  join(outRoot, 'package.json'),
  JSON.stringify({ name: '@botore/edge-vendored-combat', private: true, type: 'module' }, null, 2) +
    '\n',
);

writeFileSync(
  join(outRoot, 'README.md'),
  [
    '# Vendored pure combat packages for Edge Functions',
    '',
    'Generated by `node scripts/vendor-edge-combat.mjs`.',
    'Do not edit by hand — regenerate after changing rng / replay / combat-engine.',
    '',
    'Used by `supabase/functions/combat-v1` so Deno never depends on workspace',
    'node_modules. Golden fixtures must keep matching these sources.',
    '',
  ].join('\n'),
);

console.log(`vendor-edge-combat OK → ${outRoot}`);
